#!/usr/bin/env -S uv run --no-project python
"""omarchy-to-tinted — emit tinted-theming scheme YAML from Omarchy palettes.

The missing half of the bridge: Omarchy owns `colors.toml`, tinty owns the TUI
and terminal, and nothing converted between them. This reads an Omarchy
canonical palette and writes a tinted-theming scheme file that `tinty` can
resolve, by way of the slot mapping in `spec/omarchy-map.json`.

  omarchy-to-tinted THEME_DIR_OR_FILE [--system base24|base16] [--out-dir DIR]

Contract: spec/omarchy.md. Data only: no Omarchy file is modified, nothing from
a theme is executed, and the mapping is by key name, never by file position
(Omarchy writes red,yellow,orange; base24 is base09=orange,base0A=yellow).

Both tinted YAML dialects are supported on output. The default is the modern
one (`system:` + nested `palette:`), which is what the tinted-theming/schemes
corpus and `tinty` use.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAP_PATH = HERE.parent / "spec" / "omarchy-map.json"

# Hex, six digits, nothing else. Rejects short hex, named colors, css functions
# and URLs before any value reaches an output file.
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")
LINE = re.compile(r'^\s*([A-Za-z0-9_]+)\s*=\s*"([^"]*)"')


def load_map() -> dict:
    with MAP_PATH.open() as fh:
        return json.load(fh)


def parse_colors_toml(text: str) -> dict[str, str]:
    """Minimal parser for Omarchy's flat `key = "value"` colors.toml."""
    out: dict[str, str] = {}
    for line in text.splitlines():
        match = LINE.match(line)
        if match:
            out[match.group(1)] = match.group(2)
    return out


def find_colors_file(target: Path) -> Path:
    if target.is_file():
        return target
    candidate = target / "colors.toml"
    if candidate.is_file():
        return candidate
    raise SystemExit(f"no colors.toml at {target}")


def translate(colors: dict[str, str], spec: dict, legacy: bool) -> tuple[dict[str, str], list[str], list[str]]:
    """Return (slot -> hex, notes, warnings).

    Canonical keys resolve through the declared fallback chain. A slot the
    source genuinely cannot express is reported, never invented.
    """
    slots: dict[str, str] = {}
    notes: list[str] = []
    warnings: list[str] = []

    if legacy:
        for slot, key in spec["legacyAnsi"].items():
            value = colors.get(key)
            if value:
                slots[slot] = value
        warnings.append(
            "source exposes only ANSI color0..color15: result is a PARTIAL overlay "
            f"({len(slots)}/24 slots). ANSI numbering is not base16/base24 numbering."
        )
        return slots, notes, warnings

    for slot, chain in spec["fallback"].items():
        for key in chain:
            value = colors.get(key)
            if value is None:
                continue
            slots[slot] = value
            if key != spec["canonical"][slot]:
                notes.append(f"{slot} <- {key} (fallback; {spec['canonical'][slot]} absent)")
            break
        else:
            warnings.append(f"{slot} has no source key; left unset")

    for slot, key in spec["canonical"].items():
        value = colors.get(key)
        if value is not None and not HEX.match(value):
            raise SystemExit(f"{key} = {value!r} is not six-digit hex; refusing to translate")
    return slots, notes, warnings


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def emit_yaml(meta: dict, slots: dict[str, str], dialect: str) -> str:
    order = [f"base{i:02X}" for i in range(24)]
    present = [s for s in order if s in slots]
    header = [
        f"# {meta['name']} — translated from an Omarchy palette.",
        "#",
        "# Generated by design-system/scripts/omarchy-to-tinted.py",
        "# Contract: spec/omarchy.md. Data only; safe to regenerate.",
        f"# Source palette: {meta['source_path']}",
        f"# Source palette sha256: {meta['source_digest']}",
        f"# Omarchy map: spec/omarchy-map.json (source {meta['map_revision']})",
    ]
    if meta["notes"]:
        header.append("#")
        header.extend(f"#   fallback: {n}" for n in meta["notes"])
    if meta["warnings"]:
        header.append("#")
        header.extend(f"#   WARNING: {w}" for w in meta["warnings"])

    if dialect == "legacy":
        lines = [f'scheme: "{meta["name"]}"', f'author: "{meta["author"]}"']
        lines += [f'{s}: "{slots[s].lstrip("#").upper()}"' for s in present]
        return "\n".join(header + lines) + "\n"

    lines = [
        'system: "base24"',
        f'name: "{meta["name"]}"',
        f'author: "{meta["author"]}"',
        f'variant: "{meta["variant"]}"',
        "palette:",
    ]
    lines += [f'  {s}: "{slots[s]}"' for s in present]
    return "\n".join(header + lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("target", help="an Omarchy theme directory or a colors.toml path")
    parser.add_argument(
        "--system",
        default="base24",
        choices=["base24", "base16"],
        help="base24 keeps all 24 slots; base16 drops the 8 base24-only slots",
    )
    parser.add_argument("--dialect", default="modern", choices=["modern", "legacy"], help="output YAML dialect")
    parser.add_argument("--out-dir", help="write <slug>.yaml here; otherwise print to stdout")
    parser.add_argument("--author", default="byteowlz (omarchy adapter)")
    parser.add_argument("--name", help="scheme name; defaults to the theme directory name")
    args = parser.parse_args(argv)

    spec = load_map()
    path = find_colors_file(Path(args.target).expanduser())
    raw = path.read_bytes()
    colors = parse_colors_toml(raw.decode("utf-8"))

    canonical_present = any(key in colors for key in spec["canonical"].values())
    legacy = not canonical_present
    if not colors:
        raise SystemExit(f"{path} has no readable palette keys")

    slots, notes, warnings = translate(colors, spec, legacy)
    if args.system == "base16":
        dropped = [s for s in slots if s not in [f"base{i:02X}" for i in range(16)]]
        slots = {s: v for s, v in slots.items() if s in [f"base{i:02X}" for i in range(16)]}
        if dropped:
            warnings.append(f"base16 output drops {len(dropped)} base24-only slots: {', '.join(sorted(dropped))}")

    mode = colors.get("mode") or colors.get("theme_type") or spec["metadata"]["mode"]["default"]
    if mode not in spec["metadata"]["mode"]["allowed"]:
        raise SystemExit(f"invalid mode {mode!r}")

    name = args.name or path.parent.name
    meta = {
        "name": name,
        "author": args.author,
        "variant": mode,
        "source_path": str(path),
        "source_digest": hashlib.sha256(raw).hexdigest(),
        "map_revision": spec["source"]["revision"][:12],
        "notes": notes,
        "warnings": warnings,
    }
    text = emit_yaml(meta, slots, args.dialect)

    if args.out_dir:
        out = Path(args.out_dir).expanduser()
        out.mkdir(parents=True, exist_ok=True)
        dest = out / f"{slugify(name)}.yaml"
        dest.write_text(text)
        print(f"wrote {dest} ({len(slots)}/24 slots)", file=sys.stderr)
    else:
        sys.stdout.write(text)
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
